#!/usr/bin/env python3
"""Report which runtime-library functions (Dolphin SDK, CRI, MSL, TRK) the game code calls.

Run after `ninja`. Reads config/GF7E01/symbols.txt and the split assembly in build/GF7E01, and writes
docs/sdk_boundary.md. Every function listed is one a PC port must provide.
"""
import collections
import glob
import os
import re

VERSION = "GF7E01"
# main.dol layout (see README): game code, then the linked libraries.
RANGES = [
    (0x8000DDA0, 0x8012D438, "game"),
    (0x8012D438, 0x8015CA04, "Dolphin SDK"),
    (0x8015CA04, 0x80198B1C, "Namco engine"),  # NU Sound driver, BGM control, dvdfs, heaps
    (0x80198B1C, 0x801E8D48, "CRI ADX/Sofdec"),
    (0x801E8D48, 0x801EEFA0, "MetroTRK (debugger)"),
    (0x801EEFA0, 0x80200B20, "MSL/Runtime"),
]
FN = re.compile(r"^(\S+) = \.(?:text|init):0x([0-9A-F]+); // type:function size:0x([0-9A-F]+)")
GENERIC = re.compile(r"^(fn|gap)_")
GAME_SIDE = ("game", "Namco engine")  # code a port recompiles rather than replaces


def region(addr):
    for lo, hi, name in RANGES:
        if lo <= addr < hi:
            return name
    return "init/other"


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    addr_of, region_of = {}, {}
    for line in open(os.path.join(root, "config", VERSION, "symbols.txt"), encoding="utf-8"):
        m = FN.match(line)
        if m:
            a = int(m.group(2), 16)
            addr_of[m.group(1)] = a
            region_of[m.group(1)] = region(a)

    totals = collections.Counter(region_of.values())
    named = collections.Counter(r for n, r in region_of.items() if not GENERIC.match(n))

    calls = collections.defaultdict(lambda: collections.Counter())  # callee -> {caller module: count}
    asm = glob.glob(os.path.join(root, "build", VERSION, "asm", "*.s"))
    asm += glob.glob(os.path.join(root, "build", VERSION, "*", "asm", "*.s"))
    for path in asm:
        rel = os.path.relpath(path, os.path.join(root, "build", VERSION)).replace("\\", "/")
        module = "main" if rel.startswith("asm/") else rel.split("/")[0]
        cur = None
        for line in open(path, encoding="utf-8", errors="replace"):
            if line.startswith(".fn "):
                cur = line.split()[1].rstrip(",")
            elif cur and "\tbl " in line:
                callee = line.split("\tbl ")[1].split()[0]
                if callee not in region_of:
                    continue
                if module == "main" and region_of.get(cur) not in GAME_SIDE:
                    continue  # library-internal call
                if region_of[callee] in GAME_SIDE or region_of[callee] == "init/other":
                    continue
                calls[callee][module] += 1

    by_lib = collections.defaultdict(list)
    for callee, mods in calls.items():
        by_lib[region_of[callee]].append((callee, sum(mods.values()), sorted(mods)))

    out = ["# Runtime boundary of Star Fox: Assault (GF7E01)", "",
           "Generated by `tools/sdk_boundary.py`. These are the library functions that game code (main.dol game",
           "section and all REL modules) calls directly, which is what a PC port has to reimplement or recompile.", "",
           "## Library naming coverage", "", "| Region | Functions | Named |", "|---|---:|---:|"]
    for _, _, r in RANGES:
        out.append(f"| {r} | {totals[r]} | {named[r]} ({100 * named[r] // max(totals[r], 1)}%) |")
    out += ["", "## Functions called from game code", ""]
    for _, _, r in [x for x in RANGES if x[2] not in GAME_SIDE]:
        items = sorted(by_lib.get(r, []), key=lambda x: (-x[1], x[0]))
        unnamed = sum(1 for n, _, _ in items if GENERIC.match(n))
        out += [f"### {r}: {len(items)} functions ({unnamed} still unnamed)", "",
                "| Function | Call sites | Called from |", "|---|---:|---|"]
        for n, c, mods in items:
            out.append(f"| `{n}` | {c} | {', '.join(mods[:6])}{' …' if len(mods) > 6 else ''} |")
        out.append("")
    os.makedirs(os.path.join(root, "docs"), exist_ok=True)
    open(os.path.join(root, "docs", "sdk_boundary.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
    for _, _, r in RANGES:
        print(f"{r:22} {named[r]:5}/{totals[r]:<5} named;  called from game: {len(by_lib.get(r, []))}"
              f" ({sum(1 for n, _, _ in by_lib.get(r, []) if GENERIC.match(n))} unnamed)")


if __name__ == "__main__":
    main()
